import { AgentSpendingPolicy, PolicyCheckResult } from "./types";

/**
 * Default safe spending policy for AI agent tasks.
 * Uses NEAR testnet exclusively with conservative limits.
 */
export const DEFAULT_AGENT_SPENDING_POLICY: AgentSpendingPolicy = {
  network: "testnet",
  maxPerTransactionNear: 0.05, // 0.05 NEAR max per task
  maxDailyNear: 0.2, // 0.20 NEAR max per 24-hour window
  allowedRecipients: [
    "oracle.testnet",
    "compute-node.testnet",
    "storage-provider.testnet",
    "agent-escrow.testnet",
  ],
  enforceRecipientWhitelist: false, // Default: open to any valid testnet recipient with policy checks
};

/**
 * Validates NEAR account ID format (2-64 characters, lowercase alphanumeric + - _ .)
 */
export function isValidNearAccountId(accountId: string): boolean {
  if (!accountId || typeof accountId !== "string") return false;
  const clean = accountId.trim().toLowerCase();
  if (clean.length < 2 || clean.length > 64) return false;
  // Implicit 64-char hex account
  if (/^[0-9a-f]{64}$/.test(clean)) return true;
  // Named account
  return /^([a-z0-9_-]+\.)*[a-z0-9_-]+$/.test(clean);
}

/**
 * Validates whether an account ID is strictly a NEAR Testnet account address.
 * Testnet named accounts end with .testnet; 64-character implicit hex accounts are also allowed.
 * Mainnet .near accounts are strictly rejected.
 */
export function isTestnetAccountId(accountId: string): boolean {
  if (!isValidNearAccountId(accountId)) return false;
  const clean = accountId.trim().toLowerCase();
  if (/^[0-9a-f]{64}$/.test(clean)) return true;
  if (clean.endsWith(".testnet")) return true;
  return false;
}

/**
 * Evaluates a proposed payment against the agent's spending policy.
 *
 * IMPORTANT SECURITY NOTICE:
 * Server-side policy checks enforce limits on payment proposals generated by the agent runner.
 * They DO NOT protect against a compromised unrestricted private key with direct on-chain signing ability.
 * Wallet-owner explicit authorization is always required before execution.
 */
export function evaluateSpendingPolicy(
  amountNear: number,
  recipient: string,
  currentDailySpentNear: number,
  policy: AgentSpendingPolicy = DEFAULT_AGENT_SPENDING_POLICY
): PolicyCheckResult {
  const cleanRecipient = recipient.trim().toLowerCase();

  // 1. Strict network safety enforcement
  if (policy.network !== "testnet") {
    return {
      passed: false,
      reason: "POLICY VIOLATION: Agent is strictly restricted to NEAR testnet. Mainnet operations are disallowed.",
      perTxLimitNear: policy.maxPerTransactionNear,
      dailyLimitNear: policy.maxDailyNear,
      dailySpentNear: currentDailySpentNear,
      amountNear,
      recipient: cleanRecipient,
      network: "testnet",
    };
  }

  // 2. Validate recipient account syntax
  if (!isValidNearAccountId(cleanRecipient)) {
    return {
      passed: false,
      reason: `POLICY VIOLATION: Recipient '${cleanRecipient}' is not a valid NEAR account address.`,
      perTxLimitNear: policy.maxPerTransactionNear,
      dailyLimitNear: policy.maxDailyNear,
      dailySpentNear: currentDailySpentNear,
      amountNear,
      recipient: cleanRecipient,
      network: "testnet",
    };
  }

  if (policy.network === "testnet" && !isTestnetAccountId(cleanRecipient)) {
    return {
      passed: false,
      reason: `POLICY VIOLATION: Recipient '${cleanRecipient}' is not a valid NEAR Testnet account. Testnet accounts must end in .testnet or be a 64-character implicit account.`,
      perTxLimitNear: policy.maxPerTransactionNear,
      dailyLimitNear: policy.maxDailyNear,
      dailySpentNear: currentDailySpentNear,
      amountNear,
      recipient: cleanRecipient,
      network: "testnet",
    };
  }

  // 3. Counterparty whitelist check (if enabled)
  if (
    policy.enforceRecipientWhitelist &&
    policy.allowedRecipients &&
    policy.allowedRecipients.length > 0 &&
    !policy.allowedRecipients.includes(cleanRecipient)
  ) {
    return {
      passed: false,
      reason: `POLICY VIOLATION: Recipient '${cleanRecipient}' is not in the approved agent counterparty whitelist.`,
      perTxLimitNear: policy.maxPerTransactionNear,
      dailyLimitNear: policy.maxDailyNear,
      dailySpentNear: currentDailySpentNear,
      amountNear,
      recipient: cleanRecipient,
      network: "testnet",
    };
  }

  // 4. Per-transaction limit
  if (amountNear > policy.maxPerTransactionNear) {
    return {
      passed: false,
      reason: `POLICY VIOLATION: Requested payment (${amountNear} NEAR) exceeds the per-transaction cap (${policy.maxPerTransactionNear} NEAR).`,
      perTxLimitNear: policy.maxPerTransactionNear,
      dailyLimitNear: policy.maxDailyNear,
      dailySpentNear: currentDailySpentNear,
      amountNear,
      recipient: cleanRecipient,
      network: "testnet",
    };
  }

  // 5. Positive amount check
  if (amountNear <= 0) {
    return {
      passed: false,
      reason: "POLICY VIOLATION: Payment amount must be greater than 0 NEAR.",
      perTxLimitNear: policy.maxPerTransactionNear,
      dailyLimitNear: policy.maxDailyNear,
      dailySpentNear: currentDailySpentNear,
      amountNear,
      recipient: cleanRecipient,
      network: "testnet",
    };
  }

  // 6. Daily allowance limit
  const projectedDailyTotal = currentDailySpentNear + amountNear;
  if (projectedDailyTotal > policy.maxDailyNear) {
    return {
      passed: false,
      reason: `POLICY VIOLATION: Projected daily spending (${projectedDailyTotal.toFixed(
        4
      )} NEAR) exceeds daily allowance (${policy.maxDailyNear} NEAR). Daily spent so far: ${currentDailySpentNear.toFixed(
        4
      )} NEAR.`,
      perTxLimitNear: policy.maxPerTransactionNear,
      dailyLimitNear: policy.maxDailyNear,
      dailySpentNear: currentDailySpentNear,
      amountNear,
      recipient: cleanRecipient,
      network: "testnet",
    };
  }

  return {
    passed: true,
    reason: `Complies with agent policy: ${amountNear} NEAR <= ${policy.maxPerTransactionNear} NEAR limit. Daily allowance remaining: ${(
      policy.maxDailyNear - projectedDailyTotal
    ).toFixed(4)} NEAR.`,
    perTxLimitNear: policy.maxPerTransactionNear,
    dailyLimitNear: policy.maxDailyNear,
    dailySpentNear: currentDailySpentNear,
    amountNear,
    recipient: cleanRecipient,
    network: "testnet",
  };
}
